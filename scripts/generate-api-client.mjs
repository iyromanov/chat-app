import { readFileSync, writeFileSync } from 'node:fs';
import { format } from 'prettier';

const document = JSON.parse(readFileSync('apps/api/openapi.json', 'utf8'));
const methods = new Set([
  'get',
  'post',
  'put',
  'patch',
  'delete',
  'head',
  'options',
  'trace',
]);
const operations = [];
const ids = new Set();
for (const [path, item] of Object.entries(document.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!methods.has(method)) continue;
    const id = operation.operationId;
    if (typeof id !== 'string' || !id || ids.has(id)) {
      throw new Error(`Missing or duplicate operationId: ${method} ${path}`);
    }
    ids.add(id);
    operations.push(
      `[${JSON.stringify(id)}]: endpoints[${JSON.stringify(path)}].${method.toUpperCase()}`,
    );
  }
}

const source = `// Generated by pnpm generate. Do not edit manually.
import { wrapAsPathBasedClient, type Client } from 'openapi-fetch';
import type { paths } from './schema';

export function createOperations(client: Client<paths>) {
  const endpoints = wrapAsPathBasedClient(client);
  return { ${operations.join(',\n')} };
}
`;
writeFileSync(
  'apps/web/src/shared/api/operations.ts',
  await format(source, { parser: 'typescript', singleQuote: true }),
);
